export const useThemeStore = defineStore('theme', () => {
  const savedId = localStorage.getItem('tesim-theme') || 'apple'
  const currentThemeId = ref<string>(savedId)

  function applyTheme(id: string) {
    const theme = themes.find(t => t.id === id)
    if (!theme) return

    const root = document.documentElement
    Object.entries(theme.vars).forEach(([key, value]) => {
      root.style.setProperty(key, value)
    })

    /*  storefront 固定：页面与顶栏保持白底 */
    root.style.setProperty('--background', '#FFFFFF')
    root.style.setProperty('--surface', '#FFFFFF')
    root.style.setProperty('--surface-bright', '#FFFFFF')
    root.style.setProperty('--header-bg', '#FFFFFF')
    document.body.style.backgroundColor = '#FFFFFF'

    // Apply font family to body
    document.body.style.fontFamily = theme.vars['--font-family'] || ''

    // Remove all theme classes then add the new one
    themes.forEach(t => document.body.classList.remove(t.bodyClass))
    document.body.classList.add(theme.bodyClass)

    currentThemeId.value = id
    localStorage.setItem('tesim-theme', id)
  }

  // Apply on init
  applyTheme(savedId)

  return { currentThemeId, applyTheme, themes }
})
