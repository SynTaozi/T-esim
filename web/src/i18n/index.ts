export const i18n = createI18n({
  legacy: false,
  locale: localStorage.getItem('locale') || 'en',
  fallbackLocale: 'en',
  messages,
  warnHtmlMessage: false
  // 文案中的 @ 须写成 {'@'}，否则 vue-i18n 9 会报 Invalid linked format（见 register.emailPlaceholder）
})

export function setLocale(locale: string) {
  i18n.global.locale.value = locale as 'zh' | 'en'
  localStorage.setItem('locale', locale)
  if (typeof document !== 'undefined') {
    document.documentElement.lang = locale === 'en' ? 'en' : 'zh-CN'
  }
}

export function toggleLocale() {
  const newLocale = i18n.global.locale.value === 'zh' ? 'en' : 'zh'
  setLocale(newLocale)
}

// 获取当前语言设置（优先从 localStorage 读取，确保准确性）
export function getCurrentLocale(): string {
  return localStorage.getItem('locale') || i18n.global.locale.value || 'en'
}
